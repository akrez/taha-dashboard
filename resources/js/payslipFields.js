/**
 * مقدار یک فیلد را به عدد تبدیل می‌کند؛ در صورت غیرعددی بودن null برمی‌گرداند.
 */
export function payslipNumber(value) {
    const raw = toEnglishDigits(String(value ?? ''))
        .replace(/[,٬\s\u00a0]/g, '')
        .replace(/٫/g, '.');

    if (!/^-?\d+(?:\.\d+)?$/.test(raw)) {
        return null;
    }

    const number = Number(raw);

    return Number.isFinite(number) ? number : null;
}

/**
 * جمع عددی چند فیلد؛ فیلدهای خالی یا غیرعددی صفر در نظر گرفته می‌شوند.
 */
export function sumPayslipFields(data, keys) {
    return keys.reduce((total, key) => total + (payslipNumber(data?.[key]) ?? 0), 0);
}

/**
 * مقدار خام را برای نمایش آماده می‌کند:
 * - فیلد خالی خالی می‌ماند.
 * - مبالغ با جداکننده هزارگان و ارقام فارسی نمایش داده می‌شوند.
 * - سایر فیلدها فقط با ارقام فارسی نمایش داده می‌شوند.
 */
export function formatPayslipValue(field, value) {
    const raw = value === null || value === undefined ? '' : String(value);

    if (raw === '') {
        return '';
    }

    if (field.money) {
        const numeric = toEnglishDigits(raw)
            .replace(/[,٬\s\u00a0]/g, '')
            .replace(/٫/g, '.');

        if (/^-?\d+(?:\.\d+)?$/.test(numeric)) {
            const number = Number(numeric);

            if (Number.isFinite(number)) {
                return number.toLocaleString('fa-IR', { maximumFractionDigits: 2 });
            }
        }

        return toPersianDigits(raw);
    }

    return toPersianDigits(raw);
}
